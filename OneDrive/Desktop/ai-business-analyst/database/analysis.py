# =========================================================
# 7. FEBRUARY VS MARCH REVENUE
# =========================================================

def get_february_march_revenue():
    """
    Compare total February revenue with
    total March revenue.

    Returns:
        pandas.DataFrame:
            february_revenue
            march_revenue
            percentage_change
    """

    query = """
    SELECT

        (
            SELECT SUM(revenue)
            FROM orders
            WHERE strftime('%m', order_date) = '02'
        ) AS february_revenue,

        (
            SELECT SUM(revenue)
            FROM orders
            WHERE strftime('%m', order_date) = '03'
        ) AS march_revenue;
    """

    connection = get_connection()

    try:

        result = pd.read_sql_query(
            query,
            connection
        )

        february_revenue = result.loc[
            0,
            "february_revenue"
        ]

        march_revenue = result.loc[
            0,
            "march_revenue"
        ]

        percentage_change = (
            (
                march_revenue
                - february_revenue
            )
            / february_revenue
        ) * 100

        result["percentage_change"] = (
            percentage_change
        )

        return result

    finally:
        connection.close()


# =========================================================
# 8. FEBRUARY VS MARCH BY CATEGORY
# =========================================================

def get_category_month_comparison():
    """
    Compare February and March revenue
    for every product category.

    Returns:
        pandas.DataFrame:
            category
            february_revenue
            march_revenue
            revenue_change
            percentage_change
    """

    query = """
    SELECT

        category,

        SUM(
            CASE
                WHEN strftime('%m', order_date) = '02'
                THEN revenue
                ELSE 0
            END
        ) AS february_revenue,

        SUM(
            CASE
                WHEN strftime('%m', order_date) = '03'
                THEN revenue
                ELSE 0
            END
        ) AS march_revenue

    FROM orders

    WHERE strftime('%m', order_date)
        IN ('02', '03')

    GROUP BY category

    ORDER BY
        march_revenue - february_revenue;
    """

    connection = get_connection()

    try:

        result = pd.read_sql_query(
            query,
            connection
        )

        result["revenue_change"] = (
            result["march_revenue"]
            - result["february_revenue"]
        )

        result["percentage_change"] = (
            result["revenue_change"]
            / result["february_revenue"]
        ) * 100

        return result

    finally:
        connection.close()


