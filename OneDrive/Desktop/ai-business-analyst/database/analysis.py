# =========================================================
# 5. REVENUE BY REGION
# =========================================================

def get_revenue_by_region():
    """
    Calculate revenue for each customer region.

    Returns:
        pandas.DataFrame:
            region
            revenue
    """

    query = """
    SELECT
        c.region,
        SUM(o.revenue) AS revenue

    FROM orders o

    JOIN customers c
        ON o.customer_id = c.customer_id

    GROUP BY c.region

    ORDER BY revenue DESC;
    """

    connection = get_connection()

    try:
        result = pd.read_sql_query(
            query,
            connection
        )

        return result

    finally:
        connection.close()


